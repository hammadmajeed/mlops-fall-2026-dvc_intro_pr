from pathlib import Path
import json
import pickle
import pandas as pd
from sklearn.metrics import accuracy_score, f1_score, roc_auc_score, roc_curve

with open('models/model.pkl', 'rb') as f:
    model = pickle.load(f)  # Only load artifacts generated by trusted project code.
df = pd.read_csv('data/test.csv')
X, y = df.drop(columns=['target']), df['target']
prob = model.predict_proba(X)[:, 1]
pred = model.predict(X)
metrics = {'accuracy': round(float(accuracy_score(y, pred)), 6),
           'f1': round(float(f1_score(y, pred)), 6),
           'roc_auc': round(float(roc_auc_score(y, prob)), 6)}
Path('metrics.json').write_text(json.dumps(metrics, indent=2) + '\n')
fpr, tpr, _ = roc_curve(y, prob)
Path('plots').mkdir(exist_ok=True)
pd.DataFrame({'fpr': fpr, 'tpr': tpr}).to_csv('plots/roc.csv', index=False)
print(metrics)
